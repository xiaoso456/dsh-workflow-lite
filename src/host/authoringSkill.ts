const CONTENT = `# 设计工作流（workflow-lite）

一张图由四种节点组成：**步骤**（一段提示词，交给执行者做）、**资源**（文件、文件夹、网址、Skill、自定义文字）、**输入**（执行前问用户的问题）和它们之间的**线**。执行时图被编译成一份计划，执行者（你自己、子代理或队员）按计划一步步做，每一步只看得到自己的任务描述、连给它的资源和上游交过来的结果。

所以图的质量决定三件事：每一步拿到的信息够不够、产物能不能接上、循环跑很多轮之后文件会不会失控。

## 流程

1. **弄清目标和终点**：最终交付什么、怎么算做完、什么时候停。用户说清楚了的不要再问；目标固定就不要建输入节点。
2. **先列草图再动手**：在回复里列一张步骤表（id / 做什么 / 读什么 / 写什么 / 出边），按下面「步骤怎么拆」「产物怎么传」过一遍。用户只给了方向、没给结构时，先把草图给用户确认；用户已经给了结构或要求直接建，就直接建。
3. **用工具建图**：\`create\` → \`write_node\`（步骤）→ \`write_resource\`（资源）→ \`connect\`。**只用 \`workflow_lite\` 的动作改图**，不要直接编辑图的 JSON 文件，也不要写脚本生成：那样绕过了校验，画布上打开着的图还可能把你的改动覆盖掉。
4. **写提示词和资源说明**（见下文）。
5. **自检**：逐条过文末的清单，\`compile\` 看 problems / warnings，再以执行者的视角从头读一遍计划。
6. **汇报**：步骤表、产物的流向（谁写、谁读）、你有意保留的警告及原因。

## 步骤怎么拆

一个步骤 = 一段需要独立上下文的工作，或一个需要独立结论的判定点。每多拆一步都有代价：执行者要重新读材料，交接会丢信息，计划会变长。

**拆开的理由**（至少满足一条）：

- **需要隔离**：审查、裁判不能看到作者的推理过程（防自我认可）；或者标准必须先定死再开工（防事后改标准）。
- **分支或循环的落点**：条件边要从这一步出去，或循环要回到这一步。
- **能并行**：几件互不依赖的事可以同时做。
- **执行者不同**：要换角色、工具、Skill，或派给子代理、队员单独做。
- **一个人装不下**：材料多到一个执行者读不完。

**应该合并的情况**：

- 后一步只是读前一步的文件接着做，同一个执行者、中间没有判定 → 合成一步，提示词里分 A / B 段。
- 只做「同步现状 / 读文档 / 整理 / 交接 / 复盘 / 归档 / 更新文档」的步骤 → 并进产生这些信息的那一步：在那一步顺手更新文件，文件本身就是交接。
- 两个判定在回答同一个问题（如「验收」和「能否晋级」、「审查」和「裁决」）→ 合成一个判定步骤，只出一个判定。
- 几句话就能做完的步骤。

**判断标准**：每个步骤都要能用一句话说出「它产出什么、谁会用」。说不出来就合并或删掉。大多数工作流 3–6 步；超过 8 步时，逐个说明为什么不能合并。

## 产物怎么传

| 通道 | 怎么建 | 适合传什么 |
|---|---|---|
| 交接 | 步骤 → 步骤的线（缺省把上游这一次的执行结果交给下游） | 结论、要点、判定理由——几句话说得清的 |
| 产出 | 步骤 → 资源（整份写出）；\`write_node\` 的 \`output\` / \`outputs\` 会自动建好资源并连上 | 下游要按结构读的东西：方案、报告、清单、数据 |
| 更新 | 步骤 → 资源，\`update: true\`（先读再在原文件上改） | 跨步骤、跨轮次累积的东西：台账、问题清单、项目文档 |
| 读 | 资源 → 步骤 | 上面两种文件，以及现成的资料 |
| 全局 | 一条线都不连的资源 | 交给所有步骤：纪律、事实索引、工作区地图（见下一节） |

规则：

- **每份产出都要有人读**：从资源连线到真正需要它的步骤。只写不读的文件等于没传——下游只拿到交接里的几句话。终点步骤交给用户的成品除外。
- **逐步核对输入来源**：每个步骤要用到的信息，来自哪条交接线或哪个资源？找不到来源就补线。
- **提示词和图一致**：提示词里说要写、要改、要读的每个文件，图里都要有对应的资源和方向正确的线。只写在提示词里的文件，执行者拿不到路径约定，也不会出现在计划的读写表里。
- **产出还是更新**：每次执行都从头写出 → 产出；要保留之前的内容接着改 → 更新。同一份文件被几个步骤写时，第一个是产出，其余都是更新（不然后写的会覆盖先写的，校验报 \`resource_overwritten\`）。
- **循环里的产出每轮覆盖**。需要跨轮保留的信息（计数、当前最优、已排除的方案）只能放进「更新」的资源。
- **交接说明**（\`handoff_note\`）只写下游拿到结果后怎么用，不重复上游的内容；只需要先后顺序、不需要上游结果的线用 \`handoff: none\`。

**路径**：资源里文件、文件夹的相对路径，有步骤写它时落在产出根目录下（缺省 \`.workflow-lite/runs/<实例>/out/\`，每次执行各一份），只被读时相对工作区。要就地维护工作区里**已有**的文件（项目文档、跨执行的台账），写绝对路径；或者 \`configure\` 把 \`output_root\` 设成 \`.\`，再给每次的产出文件带上子目录。编译后看计划「资源」一节拼出来的路径是不是你要的位置。

## 全局资源（一条线都不连）

一条线都不连的资源交给每一个步骤：每一步派发时都会带上它，里面的 Skill 每一步都要先加载。所以这里只放**每一步都用得上**的东西，并且越短越好。

**适合放的**：

| 内容 | 用什么项 | 例子 |
|---|---|---|
| 执行纪律（红线） | 自定义 | 禁止的操作、授权范围（如「判定通过后直接上线，不再等确认」）、禁用的工具、每次改配置先自检生效 |
| 事实索引 | 自定义 | 哪类信息以哪个文件为准：「当前最优、逐轮对比 → \`docs/SCOREBOARD.md\`；已否决的方法 → \`docs/DEADENDS.md\`」 |
| 工作区地图 | 文件夹 | 代码、数据、日志目录及用途：「\`lab/\` 实验脚本，新脚本写这里」 |
| 全员要守的规范、参考资料 | 文件 / 网址 | 编码规范、接口文档 |
| 每一步都用得上的 Skill | Skill | 收尾前跑验证 |

**不适合放的**：

- **只有一两步用的东西**：连给那几步。比如「写文档去 AI 味」只连写文档、写报告的步骤；「逐条重读官方规则」的规则文档只连侦察那一步。放进全局，每一步都要多读一份、多加载一个 Skill。
- **某一步的流程和判据**：晋级条件写在判定步骤里，回退到哪一步由线表达。全局里再写一遍，两处迟早改得不一致。
- **会变的数字和现状**（当前最优、计数、进度）：放「更新」资源，全局里只写它在哪个文件。抄过来的数字下一轮就过期了。
- **步骤之间传递的产物**：要连线，见上一节。

**写法**：

- 按主题分成几项（纪律一项、索引一项），每条一行、编号，写成能照做的话：「禁止……」「先……再……」。可以附一句违反的后果。
- 全部全局文字控制在 60 行以内。
- **每条规则只写一处**：全局写了的，步骤提示词里不再写；目标、硬性门槛这类话也只在一处出现，别处引用。
- 工作区地图里的目录，步骤在里面写脚本、日志属于正常干活，**不要**给它连写入线——连了之后相对路径会改落到产出根目录下。要交给下游的东西另建产出资源。

一份好的全局纪律：

\`\`\`
【纪律】
① 禁止 sleep 和同步阻塞等待；后台任务用非阻塞方式取结果。
② 改任何开关先自检「开 / 关结果不同」；相同 = 没生效，先查再继续。
③ 禁止使用记忆工具；交接只靠落盘文件。
④ 判定通过后直接上线，不再等用户确认；只有用户叫停才停。
【以谁为准】当前最优、逐轮对比 → docs/SCOREBOARD.md；口径 → docs/METHODS.md §1；已否决的方法 → docs/DEADENDS.md（动手前先看）。
\`\`\`

## 资源说明怎么写

写入的文件，资源项的 \`note\`（\`outputs\` 里的 \`rule\`）是执行者写它的全部依据。要写成**规格**，不要写成愿望。

**产出（整份写）的说明写三件事：**

- **结构**：固定几节、每节放什么，能用表格就用表格。
- **长度上限**：如「≤ 80 行」「一屏以内」。给下游读的文件越短越好；长的证据（原始日志、数据、逐条输出）放进单独的文件，这里只写路径。
- **只写这一次**：每次整份重写，不保留上一次的内容，不写「比上一轮改了什么」「本轮过程」这类说明——除非这正是你要的。

**更新的说明写五件事**（这是防止文件越跑越长的关键）：

- **分区**：「现状区」（当前最优、当前配置、待办队列……）每次就地改写成最新值，**不追加**；「记录区」是一张表，每次**只加一行**。
- **一行的格式**：列出列名和每格写什么（数字、短语、证据路径），每格不超过一行。细节留在这一次的产出里，表格里只放路径。
- **谁写哪一区**：几个步骤更新同一个文件时，写清各自负责哪一区，不要两个步骤写同一件事。
- **一事一处**：同一个事实只记在一个文件的一个位置，别处引用路径，不要抄写。
- **上限与归档**：如「记录表超过 30 行时，把最早的 20 行移到 \`<名>-archive.md\`，这里留一行汇总」。

好的写法：

\`\`\`
SCOREBOARD.md（更新）。结构固定：
§0 当前最优：≤ 10 行，每轮就地改写；
§1 轮次表：每轮加一行，列 = 轮次 | 日期 | 候选 | 主指标 Δ | 判定 | 证据路径，每格 ≤ 30 字；
§2 计数：就地改写。
§1 超过 40 行时把最早的 20 行移到 SCOREBOARD-archive.md。
\`\`\`

差的写法：\`对比台账，每轮更新，信息要写全，要能复算。\`——没有结构、没有上限，执行者只能每轮追加一大段。

## 提示词怎么写

- **开头写目标和完成标准**：完成标准要能核对（数字、清单、文件存在），不要写「做得更好」。
- **写做什么和判断依据**。计划里已经有的不要再写：这一步读写哪些资源、路径、交接内容、判定行的格式（回复最后一行写 pass / fail），都由编译器写进计划。
- **用户只要求流程和标准时，不要写死具体方法**，给执行者留判断空间；必须遵守的约束写成硬规则（「不许……」）。
- **有条件出边的步骤**：分别写清 pass、fail（或每个条件）的判据。
- **循环里的步骤**：写清每轮开始先读什么（如「先读台账的现状区」），不要依赖上一轮的对话。
- **全局纪律**放进一个不连线的「自定义」资源（见「全局资源」），不要在每个提示词里重复一遍。
- **长度**：通常 10–40 行。超过 60 行时，看看是不是两件事，或者把规则抽成共享资源。

## 分支与循环

- 判定步骤的出边写 \`when\`：\`pass\` / \`fail\` 最常用，也可以写一句自然语言条件。同一步骤的出边要么都带条件、要么都不带（混用报 \`mixed_conditional_edges\`）；用 pass / fail 时两边都要接上。
- 循环 = 判定步骤指回循环入口的回边。环上必须有一条出环的条件边（否则 \`loop_without_exit\`）；「一直循环到达成目标」也要有达成时出环的那条边。
- 退出条件写死在判定步骤的提示词里，要能核对。
- 每轮的第一步先读「更新」资源里的现状区，再干活。

## 输入与设置

- **输入节点**只用于执行前必须由用户决定、每次可能不同的事。目标固定、或执行者自己能定的，不要建。
- **\`output_root\`**：缺省每个实例单独一个 \`out\` 目录（推荐，互不覆盖）；\`.\` = 工作区根目录。
- **\`mode\`**：\`serial\` 适合短而连贯的流程；步骤需要隔离（独立审查）或能并行时用 \`subagent\` / \`team\`；拿不准用 \`auto\`。
- **\`reuse\`**（复用执行者）：循环里的步骤要记住上一轮试过什么（修复类）用 \`reuse\`；每轮都要不带偏见地重看（独立审查）用 \`fresh\`；拿不准留 \`auto\`。\`serial\` 时不起作用。
- **\`set_goal\`**（设定目标，缺省开）：让主 agent 开始前把这次执行设成会话目标，长流程不会做一半就停。只有一两步的小流程可以关掉。
- **\`run_state\`**：步骤多、有循环、可能中断或要在画布上看进度时打开。

## 自检清单

建完、汇报前逐条过：

**结构**

- [ ] 每个步骤都能一句话说出产出什么、谁用；能合并的已经合并
- [ ] 没有只做同步、交接、整理文档的步骤
- [ ] 循环有出口；用 pass / fail 的判定步骤两边都接了

**产物**

- [ ] 每个产出资源都有读它的步骤（终点成品除外）
- [ ] 每个步骤要用的信息都有来源（交接线或资源）
- [ ] 提示词里提到要写、要改、要读的文件，图里都有对应的资源和线，方向（产出 / 更新 / 读）正确
- [ ] 每份文件只有一个产出者，其余是更新
- [ ] 要跨轮保留的信息在「更新」资源里，不在每轮覆盖的产出里
- [ ] 计划里拼出来的路径是你想要的位置（尤其是工作区里已有的文件）

**资源说明**

- [ ] 每个写入的文件都有说明：结构和长度上限
- [ ] 产出写明「整份重写，只写这一次」
- [ ] 更新写明现状区 / 记录区、一行的格式、归档规则
- [ ] 同一个事实只有一处
- [ ] 全局资源里只有每一步都用得上的东西；只有个别步骤用的 Skill、资料已经连给那几步
- [ ] 同一条规则没有同时写在全局和步骤提示词里

**收尾**

- [ ] \`compile\` 没有 problems；warnings 逐条处理，保留的能说出原因
- [ ] 以执行者的视角从头读一遍计划：每一步拿到的信息够不够，前后有没有矛盾

## 常见错误

- 把「读文档」「同步现状」「复盘交接」单独做成步骤。
- 把验收和晋级、审查和裁决拆成两个判定。
- 中间产出没连给下游，下游只拿到交接里的几句话。
- 提示词里写「就地更新 docs/xxx」，图里却没有对应的更新线；或者用了相对路径，改的其实是产出目录里的副本。
- 台账、现状文档每轮在开头追加一大段「本轮结果」，几轮之后上百 KB。
- 表格单元格里写整段话。
- 每轮的产出保留上一轮的内容，或写「相比上一版修改了……」。
- 直接写图的 JSON，或写脚本生成图。
- 每个提示词里都重复同一套纪律；或者全局里写了一遍，提示词里又写一遍。
- 只有一两步用的 Skill 放进全局，每一步都要加载。
- 全局里抄了当前最优、计数这些会变的数字。

## 改已有的图

- 先 \`read\` 看索引（步骤、资源、谁读谁写），再 \`read\` 带 \`node\` 读要改的节点。
- 合并步骤时，把被删步骤的读写线、交接说明搬到合并后的步骤上，再删旧步骤。
- 改完同样过一遍自检清单。
`

/**
 * 注册 skill；`skills` 服务不在时由调用方跳过。
 * @returns 注销器。
 */
export function registerAuthoringSkill(ctx: Context): () => void {
  return ctx.skills.register({
    name: AUTHORING_SKILL,
    description: DESCRIPTION,
    whenToUse: WHEN_TO_USE,
    source: 'runtime',
    content: CONTENT,
  })
}
